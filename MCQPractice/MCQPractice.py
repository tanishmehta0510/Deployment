# ================================================================ DATA MODEL
class MCQ(BaseModel):
    # No default values on purpose: Gemini's response_schema rejects/ignores defaults on some SDK
    # versions. Every field is always requested; validate() fills anything missing.
    question: str
    qtype: Literal["Single Correct", "Multiple Correct", "Numerical"]
    options: list[str]
    correct_indices: list[int]
    correct_value: Optional[float]
    explanation: str
    source: Literal["PYQ", "PYQ-style"]
    year: Optional[int]
    session: Optional[str]
    date_shift: Optional[str]


_FILL = dict(options=[], correct_indices=[], correct_value=None, explanation="",
             source="PYQ-style", year=None, session=None, date_shift=None)
_PREFIX = re.compile(r"^\s*(?:\(?[A-Da-d]\)|[A-Da-d][.)])\s+")   # "A. ", "(b) ", "C) "


def _norm(text):
    return re.sub(r"[^a-z0-9]", "", text.lower())[:90]


def validate(raw, expected_type):
    """Return a clean MCQ or None. Never trust the model's structure blindly."""
    if not isinstance(raw, dict):
        return None
    try:
        q = MCQ.model_validate({**_FILL, **raw})
    except Exception:
        return None
    if q.qtype != expected_type or not q.question.strip():
        return None
    if q.qtype == "Numerical":
        if q.correct_value is None or not math.isfinite(q.correct_value):
            return None
        q.options, q.correct_indices = [], []
        return q
    q.options = [_PREFIX.sub("", o).strip() for o in q.options]  # strip stray "A." prefixes
    idx = q.correct_indices
    if len(q.options) != 4 or not idx or len(set(idx)) != len(idx) or any(not o for o in q.options):
        return None
    if any(not 0 <= i <= 3 for i in idx):
        return None
    if q.qtype == "Single Correct" and len(idx) != 1:
        return None
    return q


