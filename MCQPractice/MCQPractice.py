def reset():
    for k in ("questions", "meta", "answers", "submitted", "started_at", "elapsed"):
        st.session_state.pop(k, None)


# ================================================================ SETUP SCREEN
if "questions" not in st.session_state:
    # No st.form here on purpose: subject -> chapter dropdowns must react instantly.
    with st.container(border=True):
        st.markdown('<div class="section-label">1 · Exam</div>', unsafe_allow_html=True)
        exam = st.selectbox("Target exam", list(EXAMS), label_visibility="collapsed")
        cfg = EXAMS[exam]

    with st.container(border=True):
        st.markdown('<div class="section-label">2 · Subject and scope</div>', unsafe_allow_html=True)
        c1, c2 = st.columns(2)
        subject = c1.selectbox("Subject", cfg["subjects"])
        has_levels = "General" not in SYLLABUS[subject]
        level_choice = c2.selectbox("Class", ["11th + 12th", "11th", "12th"], disabled=not has_levels)
        if has_levels:
            level = "11th and 12th" if level_choice == "11th + 12th" else level_choice
        else:
            level = "General"
        chapter = st.selectbox("Chapter", ["All chapters (mixed)"] + chapters_for(subject, level_choice))

    with st.container(border=True):
        st.markdown('<div class="section-label">3 · Test options</div>', unsafe_allow_html=True)
        c3, c4 = st.columns(2)
        n = c3.slider("Number of questions", 5, 30, 10)
        difficulty = c4.selectbox("Difficulty", ["As in the actual exam", "Slightly easier (warm-up)",
                                                 "Harder than the exam (stretch)"])
        pyq_mode = st.radio("Question source",
                            ["Latest PYQs (recalled by AI)", "Fresh PYQ-style questions"], horizontal=True)
        this_year = date.today().year
        years = st.multiselect("PYQ years to prefer", list(range(this_year, this_year - 8, -1)),
                               default=list(range(this_year, this_year - 3, -1)),
                               disabled=not pyq_mode.startswith("Latest"))
        if pyq_mode.startswith("Latest"):
            st.caption("⚠️ The AI recalls PYQs from memory and can misremember details or answers. Questions tagged "
                       "PYQ show the year/session it believes; verify important ones against the official paper.")

        custom = None
        if exam == "Custom / Board practice":
            m1, m2 = st.columns(2)
            custom = dict(
                correct=m1.number_input("Marks for correct", min_value=0.0, value=4.0, step=0.5),
                wrong=m2.number_input("Marks for wrong (negative = penalty)", max_value=0.0, value=-1.0, step=0.25),
            )

    # ---- marking preview (exactly what will be applied)
    plan = type_plan(cfg["mix"], n)
    with st.container(border=True):
        st.markdown('<div class="section-label">Marking scheme for this test</div>', unsafe_allow_html=True)
        st.table([
            {"Question type": t, "Count": c,
             "Correct": f"+{scheme_for(exam, subject, t, custom)['correct']:g}",
             "Wrong": f"{scheme_for(exam, subject, t, custom)['wrong']:g}",
             "Partial / option": (f"+{scheme_for(exam, subject, t, custom)['partial']:g}"
                                  if scheme_for(exam, subject, t, custom)["partial"] else "-")}
            for t, c in plan.items()
        ])
        max_marks = sum(scheme_for(exam, subject, t, custom)["correct"] * c for t, c in plan.items())
        st.caption(f"{cfg['note']}  **Maximum marks: {max_marks:g}.**")

    if st.button("Generate test 🚀", use_container_width=True, type="primary"):
        if not client:
            st.error("Add GEMINI_API_KEY to your .env file and restart.")
        elif pyq_mode.startswith("Latest") and not years:
            st.warning("Select at least one PYQ year.")
        else:
            bar = st.progress(0.0, text="Writing your questions...")
            qs = generate_questions(client, model, exam, subject, chapter, level, plan, difficulty,
                                    pyq_mode, years, lambda p: bar.progress(p, text="Writing your questions..."))
            bar.empty()
            if not qs:
                st.error("Couldn't generate valid questions. Try again, or change the model in the sidebar.")
            else:
                if len(qs) < n:
                    st.info(f"Generated {len(qs)} of {n} questions; the rest failed validation after retries.")
                st.session_state.update(
                    questions=qs,
                    meta=dict(exam=exam, subject=subject, chapter=chapter, custom=custom),
                    submitted=False,
                    started_at=time.time(),
                    test_id=st.session_state.test_id + 1,
                )
                st.rerun()

# ================================================================= TEST SCREEN
elif not st.session_state.submitted:
    qs, meta = st.session_state.questions, st.session_state.meta
    tid = st.session_state.test_id
    st.markdown(
        f'<span class="pill">{escape(meta["exam"])}</span><span class="pill">{escape(meta["subject"])}</span>'
        f'<span class="pill">{escape(meta["chapter"])}</span><span class="pill">{len(qs)} questions</span>',
        unsafe_allow_html=True,
    )
    st.caption("Answer at your own pace. Unattempted questions score 0. Your time is recorded when you submit.")

    # Form => clicking an option does not rerun the page, so no scroll jumping.
    with st.form("test"):
        for i, q in enumerate(qs):
            sc = scheme_for(meta["exam"], meta["subject"], q.qtype, meta["custom"])
            origin = pyq_origin(q)
            tag = f'{q.qtype} · +{sc["correct"]:g} / {sc["wrong"]:g}'
            if q.source == "PYQ" and origin:
                tag += f" · PYQ {origin}"
            elif q.source == "PYQ":
                tag += " · PYQ"
            else:
                tag += " · PYQ-style"

            with st.container(border=True):
                # Model-supplied text (year/session) goes through escape() because this markdown allows HTML.
                st.markdown(f'<span class="pill">Q{i + 1}</span><span class="pill">{escape(tag)}</span>',
                            unsafe_allow_html=True)
                # Native markdown (not raw HTML) so LaTeX in questions renders properly.
                st.markdown(q.question)

                key = f"a_{tid}_{i}"
                if q.qtype == "Single Correct":
                    st.radio(f"Q{i + 1}", [0, 1, 2, 3], index=None, key=key, label_visibility="collapsed",
                             format_func=lambda j, o=q.options: f"{LETTERS[j]}.  {o[j]}")
                elif q.qtype == "Multiple Correct":
                    st.caption("One or more options may be correct.")
                    for j in range(4):
                        st.checkbox(f"{LETTERS[j]}.  {q.options[j]}", key=f"{key}_{j}")
                else:
                    st.text_input("Your numerical answer", key=key, placeholder="e.g. 12 or 3.45")

        submit = st.form_submit_button("Submit test ✅", use_container_width=True)

    if submit:
        # Snapshot answers into plain state: widget keys vanish once the form is no longer rendered.
        answers = {}
        for i, q in enumerate(qs):
            key = f"a_{tid}_{i}"
            if q.qtype == "Multiple Correct":
                answers[i] = [j for j in range(4) if st.session_state.get(f"{key}_{j}")]
            else:
                answers[i] = st.session_state.get(key)
        st.session_state.answers = answers
        st.session_state.elapsed = time.time() - st.session_state.get("started_at", time.time())
        st.session_state.submitted = True
        st.rerun()

    if st.button("← Discard and start over"):
        reset()
        st.rerun()

# =============================================================== RESULT SCREEN
else:
    qs, meta, answers = st.session_state.questions, st.session_state.meta, st.session_state.answers

    rows, score, max_score = [], 0.0, 0.0
    stats = dict(ok=0, partial=0, bad=0, skip=0)
    by_type = {}
    for i, q in enumerate(qs):
        sc = scheme_for(meta["exam"], meta["subject"], q.qtype, meta["custom"])
        status, marks = grade(q, answers.get(i), sc)
        rows.append((status, marks))
        score += marks
        max_score += sc["correct"]
        stats[status] += 1
        t = by_type.setdefault(q.qtype, dict(Questions=0, Attempted=0, Correct=0, Marks=0.0))
        t["Questions"] += 1
        t["Attempted"] += status != "skip"
        t["Correct"] += status == "ok"
        t["Marks"] += marks

    attempted = len(qs) - stats["skip"]
    pct = score / max_score * 100 if max_score else 0.0
    elapsed = st.session_state.get("elapsed")
    sub = f"{pct:.0f}% · {escape(meta['exam'])} · {escape(meta['subject'])}"
    if elapsed is not None:
        sub += f" · {fmt_time(elapsed)}"
    st.markdown(f'<div class="score-card"><div class="score-main">{score:g}<span> / {max_score:g}</span></div>'
                f'<div class="score-sub">{sub}</div></div>', unsafe_allow_html=True)
    st.progress(max(0.0, min(1.0, score / max_score)) if max_score else 0.0)

    a, b, c, d, e = st.columns(5)
    a.metric("Correct", stats["ok"])
    b.metric("Partial", stats["partial"])
    c.metric("Wrong", stats["bad"])
    d.metric("Skipped", stats["skip"])
    e.metric("Accuracy", f"{stats['ok'] / attempted * 100:.0f}%" if attempted else "-")

    if len(by_type) > 1:
        st.markdown("**Section-wise**")
        st.table([{"Type": t, **v, "Marks": f"{v['Marks']:g}"} for t, v in by_type.items()])

    label = {"ok": "Correct", "partial": "Partially correct", "bad": "Wrong", "skip": "Skipped"}

    # ---- CSV export (utf-8-sig so Excel opens it cleanly)
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["Q", "Type", "Result", "Marks", "Your answer", "Correct answer", "Source", "Question"])
    for i, (q, (status, marks)) in enumerate(zip(qs, rows)):
        w.writerow([i + 1, q.qtype, label[status], f"{marks:g}", fmt_answer(q, answers.get(i)), fmt_correct(q),
                    ("PYQ " + pyq_origin(q)).strip() if q.source == "PYQ" else "PYQ-style", q.question])
    st.download_button("⬇️ Download results (CSV)", buf.getvalue().encode("utf-8-sig"),
                       file_name=f"mcq_{meta['exam'].split()[0].lower()}_{date.today().isoformat()}.csv",
                       mime="text/csv", use_container_width=True)

    st.markdown("### Review")
    show = st.radio("Show", ["All", "Wrong", "Skipped", "Correct"], horizontal=True, label_visibility="collapsed")
    want = {"All": None, "Wrong": {"bad", "partial"}, "Skipped": {"skip"}, "Correct": {"ok"}}[show]

    shown = 0
    for i, (q, (status, marks)) in enumerate(zip(qs, rows)):
        if want and status not in want:
            continue
        shown += 1
        with st.container(border=True):
            st.markdown(f'<span class="pill tag-{status}">{label[status]} · {marks:+g}</span>'
                        f'<span class="pill">{q.qtype}</span>', unsafe_allow_html=True)
            st.markdown(f"**Q{i + 1}.** {q.question}")
            if q.qtype == "Numerical":
                st.markdown(f"Your answer: {fmt_answer(q, answers.get(i))}")
                st.markdown(f"Correct answer: **{fmt_correct(q)}**")
            else:
                st.markdown(option_review(q, answers.get(i)))
            if q.source == "PYQ":
                st.caption("PYQ · " + pyq_origin(q))
            with st.expander("Explanation"):
                st.markdown(q.explanation or "No explanation provided.")
    if shown == 0:
        st.info("Nothing in this category. 🎉")

    col1, col2 = st.columns(2)
    if col1.button("🔁 Retake same test", use_container_width=True):
        st.session_state.test_id += 1        # new widget keys => blank answer sheet
        st.session_state.submitted = False
        st.session_state.started_at = time.time()
        st.session_state.pop("answers", None)
        st.session_state.pop("elapsed", None)
        st.rerun()
    if col2.button("🆕 New test", use_container_width=True):
        reset()
        st.rerun()