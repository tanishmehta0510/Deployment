def build_prompts(exam, subject, chapter, level, qtype, count, difficulty, pyq_mode, years, avoid):
    # Exam-level rules go in the system instruction; the specific request goes in the user message.
    system = f"""You are a senior paper-setter and coach for the Indian entrance exam: {exam}.
Write questions exactly in the style and depth of that exam's real papers, at this difficulty: {difficulty}.

Formatting rules:
- Write all maths, physics and chemistry notation as LaTeX inside $...$ (e.g. $\\frac{{dy}}{{dx}}$, $\\mathrm{{H_2SO_4}}$).
- Plain text and LaTeX only. No HTML, no markdown bold.
- Options must NOT carry letter prefixes such as "A." or "(a)".
- Keep the explanation to 1-3 sentences.

Question-type rules:
- "Single Correct": exactly 4 options, correct_indices has exactly one index (0-3). Randomise its position.
- "Multiple Correct": exactly 4 options, correct_indices has 1-4 indices (usually 2 or 3).
- "Numerical": options is [], correct_indices is [], correct_value holds the final numeric answer.

Previous-year-question honesty rules:
- Set source to "PYQ" and fill year / session / date_shift (for example: MHTCET 13 May Shift 1) when you
  genuinely recall that this exact question appeared in {exam}. Try to fill the session and shift whenever you
  recall them; if you are unsure of a detail, leave that field null rather than guessing.
- Otherwise write an ORIGINAL question in the exam's style with source "PYQ-style" and null year/session/date_shift.
- Never invent a session, date or shift to make a question look authentic.
Return ONLY a JSON array of question objects."""

    if pyq_mode.startswith("Latest"):
        pyq_line = (f"Prefer genuine previous-year questions from {exam}, newest first, from these years: "
                    f"{', '.join(map(str, sorted(years, reverse=True)))}. "
                    f"Fall back to PYQ-style originals where you cannot recall real ones.")
    else:
        pyq_line = "Write fresh original questions in the style of recent papers (all source = PYQ-style)."

    scope = (f"the whole {subject} syllabus (mixed chapters)" if chapter.startswith("All chapters")
             else f"the chapter '{chapter}'")
    level_line = f"Class {level}" if level in ("11th", "12th", "11th and 12th") else level
    user = "\n".join([
        f"Target exam: {exam}",
        f"Subject: {subject}",
        f"Scope: {scope}",
        f"Syllabus level: {level_line} (CBSE/NCERT, ICSE and Maharashtra HSC textbooks)",
        f"Question type: {qtype}",
        f"Number of questions: exactly {count}",
        f"Difficulty: {difficulty}",
        pyq_line,
        f"Today's date: {date.today().isoformat()}",
        f"Do not repeat or closely resemble these already-generated questions: {json.dumps(avoid)}",
    ])
    return system, user


def generate_questions(client, model, exam, subject, chapter, level, plan, difficulty, pyq_mode, years, on_progress):
    """Fill each question type up to its planned count. Invalid / duplicate / failed batches are
    retried (up to MAX_ATTEMPTS per type) instead of silently shrinking the test."""
    total = sum(plan.values())
    out, seen = [], set()

    for qtype, want in plan.items():
        got, attempts = 0, 0
        while got < want and attempts < MAX_ATTEMPTS:
            attempts += 1
            k = min(BATCH, want - got)
            avoid = [q.question[:60] for q in out][-40:]
            system, user = build_prompts(exam, subject, chapter, level, qtype, k, difficulty, pyq_mode, years, avoid)
            try:
                resp = client.models.generate_content(
                    model=model,
                    contents=user,
                    config=types.GenerateContentConfig(
                        system_instruction=system,
                        response_mime_type="application/json",
                        response_schema=list[MCQ],
                        temperature=0.7,
                    ),
                )
                items = json.loads(resp.text)
            except Exception as e:
                st.warning(f"{qtype}: attempt {attempts}/{MAX_ATTEMPTS} failed ({e})")
                time.sleep(1.5 * attempts)   # gentle backoff for rate limits
                continue
            if isinstance(items, dict):
                items = [items]
            for raw in items[:k]:
                q = validate(raw, qtype)
                if q and _norm(q.question) not in seen:
                    seen.add(_norm(q.question))
                    out.append(q)
                    got += 1
            on_progress(min(1.0, len(out) / total))

    out.sort(key=lambda q: TYPE_ORDER.index(q.qtype))  # sections in real-paper order
    return out


# ==================================================================== SCORING
def parse_number(text):
    try:
        v = float(str(text).strip().replace(",", ""))
    except ValueError:
        return None
    return v if math.isfinite(v) else None   # "nan" / "inf" are not answers


def grade(q, ans, sc):
    """-> (status, marks). status in ok / partial / bad / skip."""
    if q.qtype == "Single Correct":
        if ans is None:
            return "skip", 0.0
        return ("ok", sc["correct"]) if ans == q.correct_indices[0] else ("bad", sc["wrong"])

    if q.qtype == "Multiple Correct":
        chosen = set(ans or [])
        if not chosen:
            return "skip", 0.0
        right = set(q.correct_indices)
        if chosen - right:                       # any wrong option chosen
            return "bad", sc["wrong"]
        if chosen == right:
            return "ok", sc["correct"]
        if sc["partial"]:
            return "partial", sc["partial"] * len(chosen)
        return "bad", sc["wrong"]

    val = parse_number(ans) if ans else None     # Numerical
    if val is None:
        return "skip", 0.0
    tol = max(0.01, 1e-3 * abs(q.correct_value))
    return ("ok", sc["correct"]) if abs(val - q.correct_value) <= tol else ("bad", sc["wrong"])


def fmt_answer(q, ans):
    if q.qtype == "Numerical":
        return str(ans).strip() if ans and str(ans).strip() else "Not attempted"
    if q.qtype == "Single Correct":
        return f"{LETTERS[ans]}. {q.options[ans]}" if ans is not None else "Not attempted"
    return "; ".join(f"{LETTERS[j]}. {q.options[j]}" for j in sorted(ans)) if ans else "Not attempted"


def fmt_correct(q):
    if q.qtype == "Numerical":
        return f"{q.correct_value:g}"
    return "; ".join(f"{LETTERS[j]}. {q.options[j]}" for j in sorted(q.correct_indices))


def option_review(q, ans):
    """All four options with the correct ones ticked and the user's wrong picks crossed."""
    chosen = {ans} if isinstance(ans, int) else set(ans or [])
    right = set(q.correct_indices)
    lines = []
    for j, opt in enumerate(q.options):
        icon = "✅" if j in right else ("❌" if j in chosen else "⚪")
        you = "  ← *your answer*" if j in chosen else ""
        lines.append(f"{icon} **{LETTERS[j]}.** {opt}{you}")
    return "  \n".join(lines)


def pyq_origin(q):
    return " · ".join(str(x) for x in (q.year, q.session, q.date_shift) if x)


def fmt_time(seconds):
    m, s = divmod(int(seconds), 60)
    return f"{m} min {s:02d} s"


