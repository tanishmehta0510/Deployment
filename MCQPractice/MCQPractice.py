def scheme_for(exam, subject, qtype, custom=None):
    """Marking for one question -> dict(correct, wrong, partial). `wrong` is <= 0.
    `partial` = marks per correct option on a Multiple Correct question with no wrong option."""
    if exam == "MHT-CET (PCM)":
        return dict(correct=2.0 if subject == "Mathematics" else 1.0, wrong=0.0, partial=0.0)
    if exam == "JEE Main":
        # FIX: the old `qtype == ("Single Correct" or "Numerical")` collapses to `qtype == "Single Correct"`
        # (a non-empty string is truthy, so `or` returns the first one), so Numerical never got -1.
        return dict(correct=4.0, wrong=-1.0 if qtype in ("Single Correct", "Numerical") else 0.0, partial=0.0)
    if exam == "JEE Advanced":
        if qtype == "Single Correct":
            return dict(correct=3.0, wrong=-1.0, partial=0.0)
        if qtype == "Multiple Correct":
            return dict(correct=4.0, wrong=-2.0, partial=1.0)
        return dict(correct=4.0, wrong=0.0, partial=0.0)
    if exam == "BITSAT":
        return dict(correct=3.0, wrong=-1.0, partial=0.0)
    if exam == "KCET":
        return dict(correct=1.0, wrong=0.0, partial=0.0)
    custom = custom or {}
    return dict(correct=abs(custom.get("correct", 4.0)), wrong=-abs(custom.get("wrong", -1.0)), partial=0.0)


def type_plan(mix, n):
    """Split n questions across types by the exam's mix; remainder goes to the first type."""
    plan = {t: int(n * w) for t, w in mix.items()}
    first = next(iter(mix))
    plan[first] += n - sum(plan.values())
    return {t: c for t, c in plan.items() if c > 0}


